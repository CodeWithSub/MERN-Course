// If statement
let age = 20;

if (age >= 18) {
  console.log("You are an adult");
}

// If-else
let isLoggedIn = false;

if (isLoggedIn) {
  console.log("Welcome back");
} else {
  console.log("Please log in");
}

// If-else if-else
let score = 72;

if (score >= 90) {
  console.log("Grade: A");
} else if (score >= 80) {
  console.log("Grade: B");
} else if (score >= 70) {
  console.log("Grade: C");
} else {
  console.log("Grade: D or below");
}
